export type ErrorCode = keyof typeof ENGLISH;

/** The backend error `code` with `params` (named as in the template), ready to throw. */
export function fail(code: ErrorCode, params: Record<string, string | number> = {}): BackendError {
  const text = Object.fromEntries(Object.entries(params).map(([name, value]) => [name, String(value)]));
  return { code, params: text, message: fillTemplate(ENGLISH[code], text) };
}
